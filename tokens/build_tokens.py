#!/usr/bin/env python3
"""Generate tokens.css and tokens.json from figma-source.json.

Run from anywhere:  python3 tokens/build_tokens.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = json.loads((HERE / "figma-source.json").read_text())


def camel(parts):
    """['Neutral', 'Background', 'Subtle', 'Light alpha', 'Hover'] -> NeutralBackgroundSubtleLightAlphaHover"""
    out = []
    for p in parts:
        for w in re.split(r"[\s\-]+", p):
            if w:
                out.append(w[0].upper() + w[1:])
    return "".join(out)


def color_name(path):
    parts = path.split("/")
    if parts[-1] == "Rest":
        parts = parts[:-1]
    elif parts[-1].startswith("Rest "):
        parts[-1] = parts[-1].replace("Rest ", "Alt")
    return "color" + camel(parts)


# --- colors (light / dark) ---------------------------------------------------
colors = {}
for path, light, dark in src["color"]["rows"]:
    name = color_name(path)
    assert name not in colors, f"duplicate token name {name} from {path}"
    colors[name] = {"light": light, "dark": dark, "figma": path}

brand = {f"colorBrand{n.split('-')[1]}": v for n, v in src["brandRamp"]}

# --- layout -------------------------------------------------------------------
radius_map = {"None": "None", "Small": "Small", "Medium": "Medium", "Large": "Large",
              "X-Large": "XLarge", "Circular": "Circular"}
layout = {}
for path, val in src["layout"]:
    group, *rest = path.split("/")
    if group == "Corner radius":
        layout["borderRadius" + radius_map[rest[0]]] = f"{val}px"
    elif group == "Spacing":
        layout["spacing" + rest[0] + rest[1]] = f"{val}px"
    elif group == "Stroke width":
        layout["strokeWidth" + rest[0]] = f"{val}px"

# --- typography ---------------------------------------------------------------
size_step = {10: "Base100", 12: "Base200", 14: "Base300", 16: "Base400", 20: "Base500",
             24: "Base600", 28: "Hero700", 32: "Hero800", 40: "Hero900", 68: "Hero1000"}
line_step = {14: "Base100", 16: "Base200", 20: "Base300", 22: "Base400", 28: "Base500",
             32: "Base600", 36: "Hero700", 40: "Hero800", 56: "Hero900", 92: "Hero1000"}
weights = {"Regular": 400, "Semibold": 600, "Bold": 700}
font = {
    "fontFamilyBase": "'Segoe UI', 'Segoe UI Web (West European)', -apple-system, BlinkMacSystemFont, Roboto, 'Helvetica Neue', sans-serif",
    "fontFamilyMonospace": "Consolas, 'Courier New', Courier, monospace",
    "fontWeightRegular": "400",
    "fontWeightSemibold": "600",
    "fontWeightBold": "700",
}
for px, step in size_step.items():
    font["fontSize" + step] = f"{px}px"
for px, step in line_step.items():
    font["lineHeight" + step] = f"{px}px"

type_styles = []
for name, weight, size, lh in src["typography"]:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    type_styles.append({"name": name, "class": f"text-{slug}", "size": size_step[size],
                        "lineHeight": line_step[lh], "weight": weights[weight]})

# --- shadows (built from the Shadow/* color tokens so they flip in dark mode) --
shadows = {
    "shadow2": "0 0 2px var(--colorShadowAmbient), 0 1px 2px var(--colorShadowKey)",
    "shadow4": "0 0 2px var(--colorShadowAmbient), 0 2px 4px var(--colorShadowKey)",
    "shadow8": "0 0 2px var(--colorShadowAmbient), 0 4px 8px var(--colorShadowKey)",
    "shadow16": "0 0 2px var(--colorShadowAmbient), 0 8px 16px var(--colorShadowKey)",
    "shadow28": "0 0 8px var(--colorShadowAmbientDarker), 0 14px 28px var(--colorShadowKeyDarker)",
    "shadow64": "0 0 8px var(--colorShadowAmbientDarker), 0 32px 64px var(--colorShadowKeyDarker)",
    "shadow2Brand": "0 0 2px var(--colorShadowBrandAmbient), 0 1px 2px var(--colorShadowBrandKey)",
    "shadow4Brand": "0 0 2px var(--colorShadowBrandAmbient), 0 2px 4px var(--colorShadowBrandKey)",
    "shadow8Brand": "0 0 2px var(--colorShadowBrandAmbient), 0 4px 8px var(--colorShadowBrandKey)",
}

# Motion is not in the Figma file; values follow Fluent 2 web defaults.
motion = {
    "durationUltraFast": "50ms", "durationFaster": "100ms", "durationFast": "150ms",
    "durationNormal": "200ms", "durationGentle": "250ms", "durationSlow": "300ms",
    "durationSlower": "400ms", "durationUltraSlow": "500ms",
    "curveAccelerateMid": "cubic-bezier(1,0,1,1)", "curveDecelerateMid": "cubic-bezier(0,0,0,1)",
    "curveEasyEase": "cubic-bezier(0.33,0,0.67,1)", "curveLinear": "cubic-bezier(0,0,1,1)",
}

# --- write tokens.css --------------------------------------------------------
def block(d):
    return "\n".join(f"  --{k}: {v};" for k, v in d.items())

static = {**brand, **layout, **font, **shadows, **motion}
light = {k: v["light"] for k, v in colors.items()}
dark = {k: v["dark"] for k, v in colors.items()}

css = f"""/* Fluent 2 Web — design tokens
 * Generated by tokens/build_tokens.py from figma-source.json. Do not edit by hand.
 * Source: {src['source']['url']}
 *
 * Light is the default. Dark applies with <html data-theme="dark">, or follows the OS
 * when no data-theme is set. Force light with <html data-theme="light">.
 */

:root {{
{block(static)}
}}

:root,
:root[data-theme="light"] {{
  color-scheme: light;
{block(light)}
}}

@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
    color-scheme: dark;
{chr(10).join('  ' + l for l in block(dark).splitlines())}
  }}
}}

:root[data-theme="dark"] {{
  color-scheme: dark;
{block(dark)}
}}

/* Type ramp utility classes (Figma text styles) */
"""
for t in type_styles:
    css += (f".{t['class']} {{ font-family: var(--fontFamilyBase); font-size: var(--fontSize{t['size']}); "
            f"line-height: var(--lineHeight{t['lineHeight']}); font-weight: {t['weight']}; }}\n")

(HERE / "tokens.css").write_text(css)

# --- write tokens.json (flat, tool-friendly) ---------------------------------
out = {
    "$source": src["source"],
    "color": colors,
    "brandRamp": brand,
    "layout": layout,
    "typography": {"tokens": font, "styles": type_styles},
    "shadow": shadows,
    "shape": {"modes": src["shape"]["modes"],
              "tokens": {r[0]: dict(zip(src["shape"]["modes"], r[1:])) for r in src["shape"]["rows"]}},
    "motion": motion,
}
(HERE / "tokens.json").write_text(json.dumps(out, indent=2))
# Same data as a script, so pages opened from file:// can read it without fetch()
(HERE / "tokens.js").write_text("// Generated by build_tokens.py\nwindow.FLUENT_TOKENS = " + json.dumps(out) + ";\n")
print(f"{len(colors)} color tokens, {len(brand)} brand ramp, {len(layout)} layout, "
      f"{len(font)} font, {len(type_styles)} type styles, {len(shadows)} shadows")
